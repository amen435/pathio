function setupClickHandlers() {
    // Override the native links generated by the path component so we can open the panel
    document.querySelectorAll('.path-row').forEach(row => {
        if (!row.classList.contains('locked')) {
            row.removeAttribute('onclick'); // prevent full page navigation
            
            row.addEventListener('click', () => {
                // Determine week number from text
                const weekTag = row.querySelector('.week-tag');
                if (weekTag) {
                    const match = weekTag.textContent.match(/WEEK\s+(\d+)/);
                    if (match) {
                        openWeekDetail(match[1]);
                    }
                }
            });
        }
    });
}

